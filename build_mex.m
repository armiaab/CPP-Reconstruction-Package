here      = fileparts(mfilename('fullpath'));
build_dir = fullfile(here, 'build_msvc');

nlopt_inc       = fullfile(build_dir, '_deps', 'nlopt-src',    'src', 'api');
nlopt_build_inc = fullfile(build_dir, '_deps', 'nlopt-build');
nlopt_lib       = fullfile(build_dir, '_deps', 'nlopt-build',  'nlopt.lib');
eigen_inc       = fullfile(build_dir, '_deps', 'eigen3_dl-src');

assert(exist(nlopt_lib, 'file') == 2, 'nlopt.lib not found. Run build.bat first.');
assert(exist(nlopt_inc, 'dir') == 7,  'NLopt include dir not found.');
assert(exist(eigen_inc, 'dir') == 7,  'Eigen3 include dir not found.');

fprintf('Building langevin_mex.mexw64 ...\n');

mex('-R2018a', ...
    '-DLANGEVIN_STATIC', ...
    '-D_USE_MATH_DEFINES', ...
    '-D_CRT_SECURE_NO_WARNINGS', ...
    ['-I' here], ...
    ['-I' nlopt_inc], ...
    ['-I' nlopt_build_inc], ...
    ['-I' eigen_inc], ...
    fullfile(here, 'langevin_mex.cpp'), ...
    fullfile(here, 'langevin_core.cpp'), ...
    fullfile(here, 'gsl_impl.cpp'), ...
    nlopt_lib, ...
    '-outdir', here);

fprintf('Done. MEX written to: %s\n', fullfile(here, ['langevin_mex.' mexext]));
